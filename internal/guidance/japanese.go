package guidance

import i "github.com/pirakansa/avera/internal/inventory"

// ForLanguage supplies bundled presentation text without changing assessment rules.
func ForLanguage(kind i.Kind, language string) Content {
	if language != "ja" {
		return For(kind)
	}
	switch kind {
	case i.Forwarding:
		return Content{"宛先転送・リダイレクトの設定を観測しました。実際の到達性を検証したものではありません。", "入口と内部の転送先を確認してください。上位の防壁があっても設定は調査対象に残します。", []string{"入口のポート・インターフェース・接続元条件と転送先は何ですか？", "ループバック上のサービスにつながりますか？該当サービスを選び、経路を説明してください。", "上位ルーターやクラウド側でどう制限していますか？保護策の根拠と残るリスクを記載して判断してください。"}}
	case i.Endpoint:
		return Content{"ローカルのネットワーク接続口を観測しました。外部から到達できることを示すものではありません。", "このサービスが必要な理由と、利用者・アクセスの保護方法を確認してください。", []string{
			"何のためのサービスですか？公開する静的コンテンツですか、それとも機密情報を受け取りますか？",
			"誰が利用しますか？どのネットワークや利用者からのアクセスを許可する必要がありますか？",
			"どのような保護策がありますか？意図的に公開するコンテンツでは認証が不要な場合もあります。その理由と他の保護策を説明してください。",
			"外部ファイアウォールで制限していますか？人による申告として記録し、設定や設計の根拠を添えてください。",
			"説明を裏付ける証拠と残るリスクは何ですか？次の対応を誰が判断しますか？",
		}}
	case i.Rule:
		return Content{"sudo の設定ルールを観測しました。実効権限のすべてを証明するものではありません。", "この権限が必要か、適切に範囲を限定できているかを確認してください。", []string{
			"この権限を誰が使いますか？ローカルで確認できたグループメンバーも確認してください。",
			"どの業務・機能のためにこの権限が必要ですか？",
			"対象ユーザー、コマンド、引数の範囲は何ですか？さらに限定できますか？",
			"どのような保護策があり、どの設定・運用の証拠で裏付けられますか？",
			"解釈や利用者の特定にどのような制約が残っていますか？判断前に誰が確認できますか？",
		}}
	case i.Unparsed:
		return Content{"sudo の設定を完全には解釈できませんでした。", "未対応の設定には人による確認が必要です。この結果だけで実効権限を判断できません。", []string{
			"sudo ポリシー全体の文脈で、この設定を誰が解釈できますか？",
			"利用者、対象ユーザー、コマンド、必要な機能と制限を説明してください。",
			"保護策と、それを裏付ける証拠を提示できますか？",
		}}
	default:
		return Content{"確認が必要な観測結果です。", "収集機能の担当者に意味を確認してください。", []string{"この項目を解釈し、裏付けとなる証拠を示せる人は誰ですか？"}}
	}
}
